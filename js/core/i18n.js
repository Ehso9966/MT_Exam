  function init() {
    currentLang = 'my';
    try {
      var m = /[?&]lang=(en|my)/.exec(window.location.search || '');
      if (m) currentLang = m[1];
      else {
        var saved = localStorage.getItem(STORAGE_KEY);
        currentLang = saved === 'en' ? 'en' : 'my';
      }
    } catch (e) { /* ignore */ }
  }

  function getLang() { return currentLang; }

  function setLang(lang) {
    currentLang = lang === 'en' ? 'en' : 'my';
    localStorage.setItem(STORAGE_KEY, currentLang);
    applyDOM();
    MT.Events.emit(MT.EVENTS.LANG_CHANGED, { lang: currentLang });
  }

  function toggle() { setLang(currentLang === 'en' ? 'my' : 'en'); }

  function t(key, vars) {
    var dict = strings[currentLang] || {};
    var val = dict[key];
    if (val === undefined) { val = (strings.en || {})[key] || key; }
    if (vars) {
      Object.keys(vars).forEach(function (k) {
        val = String(val).replace('{{' + k + '}}', vars[k]);
      });
    }
    return val;
  }

